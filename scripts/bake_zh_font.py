"""Bake the Traditional Chinese glyphs the game uses into src/data/fontZh.ts.

Source font: 俐方體11號 (Cubic 11) by ACh-K, SIL Open Font License 1.1
(https://github.com/ACh-K/Cubic-11). Only the characters found in src/ are
kept, as 12x13 bitmaps; the license travels with them in public/licenses/Cubic-11-OFL.txt.

Usage (dev only; needs `pip install fonttools`):
    python3 scripts/bake_zh_font.py path/to/Cubic_11.ttf
Re-run whenever new Chinese text is added; tests/i18n.test.ts fails on missing glyphs.
"""
import pathlib
import re
import sys

from fontTools.pens.recordingPen import RecordingPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'src' / 'data' / 'fontZh.ts'
UNIT = 100            # font units per pixel
BOX_X = (100, 1300)   # 12 columns (ideographs use the first 11; box rules join up)
BOX_Y = (1000, -300)  # 13 rows, top to bottom (baseline at row 10; brackets reach the edges)
# Already drawn by the 8x8 font (src/graphics/Font.ts).
LATIN_EXTRA = set('▶♥←→↑↓◆◇×·')


def wanted_chars():
    chars = set()
    for p in (ROOT / 'src').rglob('*.ts'):
        if p == OUT:
            continue
        for lit in re.findall(r"'(?:[^'\\\n]|\\.)*'|`[^`]*`", p.read_text(encoding='utf-8')):
            chars.update(c for c in lit if ord(c) > 0x7f and c not in LATIN_EXTRA)
    return sorted(chars)


def winding(contours, x, y):
    w = 0
    for pts in contours:
        for (x0, y0), (x1, y1) in zip(pts, pts[1:] + pts[:1]):
            if y0 <= y < y1 and (x1 - x0) * (y - y0) - (x - x0) * (y1 - y0) > 0:
                w += 1
            elif y1 <= y < y0 and (x1 - x0) * (y - y0) - (x - x0) * (y1 - y0) < 0:
                w -= 1
    return w


def main(path):
    font = TTFont(path)
    cmap, glyphs = font.getBestCmap(), font.getGlyphSet()
    chars, rows_hex, missing = [], [], []
    for ch in wanted_chars():
        name = cmap.get(ord(ch))
        if name is None:
            missing.append(ch)
            continue
        pen = RecordingPen()
        glyphs[name].draw(pen)
        contours, cur = [], []
        for op, args in pen.value:
            if op == 'moveTo':
                cur = [args[0]]
            elif op == 'lineTo':
                cur.append(args[0])
            elif op in ('closePath', 'endPath'):
                contours.append(cur)
            else:
                raise SystemExit(f'{ch}: unexpected curve segment {op}')
        bits = []
        for py in range(BOX_Y[0], BOX_Y[1], -UNIT):
            m = 0
            for i, px in enumerate(range(BOX_X[0], BOX_X[1], UNIT)):
                if winding(contours, px + UNIT / 2, py - UNIT / 2):
                    m |= 1 << (11 - i)
            bits.append(m)
        # warn if ink falls outside the 12x13 box
        outside = any(winding(contours, px + 50, py - 50)
                      for py in range(1200, -500, -UNIT) for px in range(-100, 1500, UNIT)
                      if not (BOX_X[0] <= px < BOX_X[1] and BOX_Y[1] < py <= BOX_Y[0]))
        if outside:
            print(f'warning: {ch} U+{ord(ch):04X} has pixels outside the 12x13 box', file=sys.stderr)
        chars.append(ch)
        rows_hex.append(''.join(f'{m:03x}' for m in bits))
    if missing:
        raise SystemExit('missing in font: ' + ''.join(missing))
    body = '\n'.join(f"  '{''.join(rows_hex[i:i + 8])}' +" for i in range(0, len(rows_hex), 8)).rstrip(' +')
    OUT.write_text(
        '// Generated by scripts/bake_zh_font.py - do not edit by hand.\n'
        '// Glyphs from 俐方體11號 (Cubic 11), SIL Open Font License 1.1: see public/licenses/Cubic-11-OFL.txt.\n'
        '// Each glyph is 13 rows of 12 pixels, 3 hex digits per row (bit 11 = leftmost pixel).\n'
        f"export const ZH_CHARS = '{''.join(chars)}';\n"
        f'export const ZH_BITS =\n{body};\n',
        encoding='utf-8',
    )
    print(f'{len(chars)} glyphs -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main(sys.argv[1])
