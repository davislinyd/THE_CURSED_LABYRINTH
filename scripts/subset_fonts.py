"""Subset the UI fonts to the characters the game uses -> public/fonts/*.woff2.

Fonts (SIL Open Font License 1.1, no Reserved Font Names):
  Cinzel         https://github.com/NDISCOVER/Cinzel        (Latin titles and text)
  Noto Serif TC  https://github.com/notofonts/noto-cjk      (Traditional Chinese)
The variable weight axis is kept. Licenses are copied to public/licenses/.

Usage (dev only; needs `pip install fonttools brotli`):
    python3 scripts/subset_fonts.py assets-src/fonts
where the folder holds Cinzel.ttf, NotoSerifTC.ttf and their *-OFL.txt files
(from https://github.com/google/fonts, ofl/cinzel and ofl/notoseriftc).
Re-run whenever new Chinese text is added; tests/i18n.test.ts fails on missing glyphs.
"""
import pathlib
import re
import shutil
import sys

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'public' / 'fonts'
LICENSES = ROOT / 'public' / 'licenses'
CHARS_TS = ROOT / 'src' / 'data' / 'fontChars.ts'


def used_chars():
    chars = set(chr(c) for c in range(0x20, 0x7f))
    for p in (ROOT / 'src').rglob('*.ts'):
        if p == CHARS_TS:
            continue
        for lit in re.findall(r"'(?:[^'\\\n]|\\.)*'|`[^`]*`", p.read_text(encoding='utf-8')):
            chars.update(c for c in lit if ord(c) > 0x7f)
    return chars


def make(src, dst, chars):
    font = TTFont(src)
    cmap = font.getBestCmap()
    have = {c for c in chars if ord(c) in cmap}
    opts = subset.Options()
    opts.flavor = 'woff2'
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    sub = subset.Subsetter(opts)
    sub.populate(text=''.join(sorted(have)))
    sub.subset(font)
    font.flavor = 'woff2'
    font.save(dst)
    return have


def main(src_dir):
    src_dir = pathlib.Path(src_dir)
    OUT.mkdir(parents=True, exist_ok=True)
    LICENSES.mkdir(parents=True, exist_ok=True)
    chars = used_chars()
    latin = make(src_dir / 'Cinzel.ttf', OUT / 'cinzel.woff2', chars)
    cjk = make(src_dir / 'NotoSerifTC.ttf', OUT / 'noto-serif-tc.woff2', chars)
    missing = sorted(c for c in chars if c not in latin and c not in cjk)
    if missing:
        raise SystemExit('missing in both fonts: ' + ''.join(missing))
    shutil.copy(src_dir / 'Cinzel-OFL.txt', LICENSES / 'Cinzel-OFL.txt')
    shutil.copy(src_dir / 'NotoSerifTC-OFL.txt', LICENSES / 'NotoSerifTC-OFL.txt')
    # The drawable character set, for tests/i18n.test.ts.
    drawable = ''.join(sorted((latin | cjk) - set(chr(c) for c in range(0x20, 0x7f))))
    CHARS_TS.write_text(
        '// Generated by scripts/subset_fonts.py - do not edit by hand.\n'
        '// Non-ASCII characters present in the subset UI fonts (public/fonts).\n'
        f"export const FONT_CHARS = '{drawable}';\n",
        encoding='utf-8',
    )
    for f in sorted(OUT.iterdir()):
        print(f'{f.relative_to(ROOT)}: {f.stat().st_size // 1024} KB')
    print(f'{len(chars)} characters')


if __name__ == '__main__':
    main(sys.argv[1])
